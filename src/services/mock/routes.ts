const paths = new Map<string, ReturnType<typeof createRoutePath>>();

/** Reutiliza uma geometria local por destino; nunca consulta um serviço em runtime. */
export function getMockRoadRoute(receiverId: string): ReturnType<typeof createRoutePath> {
  const cached = paths.get(receiverId);
  if (cached) return cached;
  const fixture = MOCK_ROAD_ROUTES[receiverId];
  if (!fixture) throw new Error(`Unknown mock road route: ${receiverId}`);
  const path = deepFreeze(createRoutePath(fixture.points));
  paths.set(receiverId, path);
  return path;
}
